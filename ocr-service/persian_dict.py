# موتور حرف اول را «ب» به‌جای «پ» خوانده باشد هم کاندیدو پیدا می‌شود. این کار
# جست‌وجو را از هزاران مقایسه به چند ده مقایسه کاهش می‌دهد.
_LETTER_CLASS = {}
for _i, _group in enumerate(LETTER_SETS):
    for _ch in _group:
        _LETTER_CLASS.setdefault(_ch, f's{_i}')


def _class_of(ch):
    return _LETTER_CLASS.get(ch, 'c' + ch)


_BY_BUCKET = {}
for _variant, _canon in INDEX.items():
    if not _variant:
        continue
    # مجموعهٔ نویسه‌ها برای ردِ سریع کاندیدهای بی‌ربط (پیش از محاسبهٔ فاصله)
    _BY_BUCKET.setdefault((len(_variant), _class_of(_variant[0])), []).append(
        (_variant, _canon, frozenset(_variant))
    )
_BY_BUCKET_SIZE = max((len(v) for v in _BY_BUCKET.values()), default=0)

# «هستهٔ پرتکرار»: واژه‌های پایهٔ فاکتور (شرح کالا، جمع‌ها، واحدها، برندها).
# فقط اصلاح به سمت این واژه‌ها با یک ویرایش کامل مجاز است؛ واژه‌های تازه‌تر
# (نام شهر، برند، کالای کم‌کاربرد) تنها با «جابه‌جایی حرف هم‌شکل» جای واژهٔ
# اصلی را می‌گیرند. بدون این محدودیت، واژهٔ درستِ خارج از واژه‌نامه به نزدیک-
# ترین همسایه «اصلاح» می‌شد: «سالن» → «سال»، «کشی» → «کیش».
_CORE = set(INVOICE_WORDS) | set(CONTACT_WORDS) | set(DATE_WORDS) | set(NUMBER_WORDS) \
    | set(PRODUCT_WORDS) | set(COMMON_WORDS) | set(BRAND_WORDS)
FREQUENT = {word for word in _CORE if word in INDEX.values()}


def is_known(word):
    return normalize_chars(word) in INDEX


def canon_of(word):
    return INDEX.get(normalize_chars(word))


# ------------------------------------------------------------------ فاصله
def _confusion_cost(a, b):
    if a == b:
        return 0.0
    for group in LETTER_SETS:
        if a in group and b in group:
            return CONFUSION_COST
    return 1.0


def weighted_distance(a, b, limit=2.0):
    """
    فاصلهٔ ویرایشی وزن‌دار (Damerau) با هزینهٔ کم برای حروف هم‌شکل.

    a و b از قبل یکسان‌سازی شده‌اند. اگر فاصله از limit بیشتر شد، همان limit
    برگردانده می‌شود تا محاسبه زودتر تمام شود.
    """
    if a == b:
        return 0.0
    la, lb = len(a), len(b)
    if abs(la - lb) > 2:
        return limit + 1
    prev2 = None
    prev = [j * 1.0 for j in range(lb + 1)]
    for i in range(1, la + 1):
        cur = [i * 1.0] + [0.0] * lb
        for j in range(1, lb + 1):
            sub = prev[j - 1] + _confusion_cost(a[i - 1], b[j - 1])
            cur[j] = min(sub, prev[j] + 1.0, cur[j - 1] + 1.0)
            if i > 1 and j > 1 and a[i - 1] == b[j - 2] and a[i - 2] == b[j - 1]:
                swap = prev2[j - 2] + 0.5
                if swap < cur[j]:
                    cur[j] = swap
        prev2, prev = prev, cur
    return min(prev[lb], limit + 1)


def _best_candidate(token):
    """نزدیک‌ترین واژهٔ واژه‌نامه با فاصلهٔ وزن‌دار (از سبد طول + دستهٔ حرف اول)."""
    token = normalize_chars(token)
    if not token:
        return None, 99.0
    best = (None, 99.0)
    cls = _class_of(token[0])
    token_set = frozenset(token)
    for length in (len(token) - 1, len(token), len(token) + 1):
        if length < MIN_WORD_LEN:
            continue
        for variant, canon, variant_set in _BY_BUCKET.get((length, cls), ()):
            # با سقف ویرایش ۱، بیشتر از ۴ نویسهٔ متفاوت ممکن نیست؛ ردِ ارزان
            if len(token_set ^ variant_set) > 4:
                continue
            cost = weighted_distance(token, variant)
            if cost < best[1]:
                best = (canon, cost)
                if cost <= 0.0:
                    return best
    return best


def split_merged(token):
    """
    واژهٔ چسبیده را به دو واژهٔ شناخته‌شده می‌شکند: «کابلیک» → «کابل یک».

    این حالت وقتی پیش می‌آید که موتور، فاصلهٔ بین دو واژه را نمی‌بیند؛ در
    فاکتور زیاد رخ می‌دهد («هارد۵۰۰» یا «کابلیک متری»).
    """
    token = normalize_chars(token)
    n = len(token)
    if n < 5:
        return None
    for cut in range(3, min(n - 2, MAX_SPLIT_PART) + 1):
        left, right = token[:cut], token[cut:]
        if len(right) > MAX_SPLIT_PART:
            continue
        left_canon = INDEX.get(left)
        right_canon = INDEX.get(right)
        if left_canon and right_canon:
            return f'{left_canon} {right_canon}'
    return None


from functools import lru_cache as _lru_cache


@_lru_cache(maxsize=16384)
def _correct_cached(token, allow_split):
    return _correct_token(token, allow_split)


def correct_token(token, allow_split=True):
    """یک واژه را با واژه‌نامه مقایسه و در صورت اطمینان اصلاح می‌کند (با کش)."""
    return _correct_cached(token, allow_split)


def _correct_token(token, allow_split):
    if not token:
        return token
    # رقم‌دارها واژه نیستند (مثل «E14» یا «۲۵۶گیگ»)
    if any(ch.isdigit() or ch in FA_DIGITS or ch in AR_DIGITS for ch in token):
        return token
    plain = normalize_chars(token)
    if plain in INDEX:
        return INDEX[plain]
    if len(plain) < MIN_WORD_LEN:
        return token

    canon, cost = _best_candidate(plain)
    if canon is not None:
        if cost <= MAX_COST_CONFUSION_ONLY:
            return canon
        # یک ویرایش کامل فقط برای واژه‌های ۴ نویسه و بیشتر و فقط اگر مقصد در
        # هستهٔ پرتکرار باشد («تعدا» → «تعداد»)؛ وگرنه واژه دست‌نخورده می‌ماند.
        if cost <= MAX_COST_LONG_WORD and len(plain) >= 4 and canon in FREQUENT:
            return canon

    if allow_split:
        split = split_merged(plain)
        if split:
            return split
    return token


# ------------------------------------------------------------------ ارقام
_NUMERIC_TOKEN = re.compile(r'[0-9۰-۹٠-٩][0-9۰-۹٠-٩٬،,.٫/\-]*')


def has_digit(text):
    return bool(re.search(r'[0-9۰-۹٠-٩]', text))


def repair_number_token(token):
    """
    توکنی که باید عدد باشد را اصلاح می‌کند.

    فقط وقتی دست می‌زند که دست‌کم یک رقم واقعی در توکن باشد و همهٔ نویسه‌های
    دیگرش «شبیه رقم» باشند؛ در نتیجه «SO» یا «B» به عدد تبدیل نمی‌شوند.
    خط ارقام یکدست می‌شود: توکنی که رقم لاتین دارد لاتین می‌ماند و توکن
    فارسی/عربی به فارسی تبدیل می‌شود، تا «1O5» به «1۰5» تبدیل نشود.
    """
    if not token or not has_digit(token):
        return token

    has_latin = any(ch in LATIN_DIGITS for ch in token)
    has_persian = any(ch in FA_DIGITS or ch in AR_DIGITS for ch in token)
    target_latin = has_latin or not has_persian

    out = []
    changed = False
    for ch in token:
        if ch in LATIN_DIGITS:
            out.append(ch)
        elif ch in FA_DIGITS or ch in AR_DIGITS:
            digit = ch.translate(FA_TO_LATIN)
            converted = digit if target_latin else digit.translate(LATIN_TO_FA)
            out.append(converted)
            changed = changed or converted != ch
        elif ch in NUMBER_LOOKALIKE:
            digit = NUMBER_LOOKALIKE[ch].translate(FA_TO_LATIN)
            out.append(digit if target_latin else digit.translate(LATIN_TO_FA))
            changed = True
        elif ch in '٬،,.٫/-':
            out.append(ch)
        else:
            return token  # نویسهٔ غیرعددی واقعی: دست نمی‌زنیم
    return ''.join(out) if changed else token


def repair_numbers(text):
    """اصلاح شماره‌های مخدوش در یک خط متن («1O5» → «۱۰۵»)."""
    def repl(match):
        return repair_number_token(match.group(0))
    # فقط توکن‌های چسبیده بررسی می‌شوند؛ فاصله‌ها دست‌نخورده می‌مانند
    return re.sub(r'[0-9۰-۹٠-٩OoDQIl|iZzSsGbgqTB$!.,٬،/]+', repl, text)


def to_latin_number(text):
    """عدد فارسی/عربی → عدد لاتین (برای محاسبه)."""
    return text.translate(FA_TO_LATIN)


# ------------------------------------------------------- موتور اعداد ایرانی
# هر شکلی که عدد در فاکتور ایرانی نوشته می‌شود باید یک عدد دربیاید:
#   «۱٬۲۳۴٬۵۶۷» «1,234,567» «۱۲۳۴۵۶۷» «۱ ۲۳۴ ۵۶۷» «١٢٣٤٥٦٧»
#   «۱۲۳۴۵۶۷/۰» «۲.۵ میلیون» «دو میلیون و پانصد هزار» «(۱٬۲۰۰)» «−۵۰۰»
#   «۱۲۳/۴۵۶» (سپس ارقام نه‌گانهٔ لاتین/فارسی قاطی: «1۲3»)
CURRENCY_WORDS = (
    'ریال', 'ریال‌ها', 'تومان', 'تومانی', 'تومن', 'دلار', 'یورو', 'درهم',
    'ر.س', 'ر.ی', '﷼', 'IRR', 'IRT', 'USD', 'EUR', 'ریالِ',
)

# حرف‌هایی که در فونت چاپی جای رقم می‌نشینند — فقط داخل توکن عددی
_DIGIT_LOOKALIKE = {
    'O': '0', 'o': '0', 'D': '0', 'Q': '0', 'Ο': '0', 'ө': '0',
    'I': '1', 'l': '1', '|': '1', '!': '1', 'i': '1', 'ة': None,
    'Z': '2', 'z': '2', 'Ƨ': '2',
    'A': '4', 'S': '5', 's': '5', '$': '5', 'G': '6', 'b': '6',
    'T': '7', 'B': '8', 'g': '9', 'q': '9',
}
_DIGIT_LOOKALIKE = {k: v for k, v in _DIGIT_LOOKALIKE.items() if v is not None}

_SEP_CHARS = ' \u00a0\u2009\u2007\u202f٬،,'
_UNIT_SCALES = (
    ('تریلیون', 10 ** 12), ('هزار میلیارد', 10 ** 12), ('میلیارد', 10 ** 9),
    ('میلیون', 10 ** 6), ('هزار', 10 ** 3),
)

_ONES = {
    'صفر': 0, 'یک': 1, 'دو': 2, 'سه': 3, 'چهار': 4, 'پنج': 5, 'شش': 6,
    'شیش': 6, 'هفت': 7, 'هشت': 8, 'نه': 9, 'ده': 10, 'یازده': 11, 'دوازده': 12,
    'سیزده': 13, 'چهارده': 14, 'پانزده': 15, 'پونزده': 15, 'شانزده': 16,
    'شونزده': 16, 'هفده': 17, 'هیفده': 17, 'هجده': 18, 'هیجده': 18, 'نوزده': 19,
    'بیست': 20, 'سی': 30, 'چهل': 40, 'پنجاه': 50, 'شصت': 60, 'هفتاد': 70,
    'هشتاد': 80, 'نود': 90,
    'صد': 100, 'یکصد': 100, 'دویست': 200, 'سیصد': 300, 'چهارصد': 400,
    'پانصد': 500, 'پونصد': 500, 'ششصد': 600, 'شیشصد': 600, 'هفتصد': 700,
    'هشتصد': 800, 'نهصد': 900,
}
_NUMBER_WORD_KEYS = set(_ONES) | {scale for scale, _ in _UNIT_SCALES} | {'و', 'نیم', 'دهم'}


def normalize_number_text(text):
    """ارقام فارسی/عربی و حرف‌های شبیه‌رقم را یکدست می‌کند (فقط محتوای عددی)."""
    if text is None:
        return ''
    raw = str(text).translate(FA_TO_LATIN)
    for word in CURRENCY_WORDS:
        raw = raw.replace(word, ' ')
    raw = raw.replace('٫', '.').replace('\u066b', '.')
    return raw.strip()


def _digits_of(text):
    """هر نویسهٔ «شبیه رقم» را به رقم لاتین تبدیل می‌کند؛ بقیه را نگه می‌دارد."""
    return ''.join(_DIGIT_LOOKALIKE.get(ch, ch) for ch in text)


def parse_number_words(text):
    """
    عدد نوشتاری فارسی → عدد: «دو میلیون و پانصد هزار» → 2500000.

    هر واژهٔ ناشناخته نادیده گرفته می‌شود؛ اگر هیچ عددی پیدا نشود، None.
    """
    if not text:
        return None
    words = re.sub(r'[^\u0600-\u06FF\u200c ]', ' ', normalize_chars(str(text))).split()
    total = 0
    current = 0
    seen = False
    has_number_word = False
    for word in words:
        if word in ('و',):
            continue
        if word in _ONES:
            current += _ONES[word]
            seen = has_number_word = True
            continue
        scale = None
        for name, value in _UNIT_SCALES:
            if word == name.replace(' ', ''):
                scale = value
                break
        if scale:
            total += (current or 1) * scale
            current = 0
            seen = True
    # «هزار» تنها یا «میلیون» تنها عدد نیست؛ شماره‌ای پشتش نبوده است
    if not seen or not has_number_word:
        return None
    return total + current


def parse_amount(text, allow_words=True):
    """
    متن → مبلغ صحیح، یا None.

    همهٔ شکل‌های رایج پذیرفته می‌شوند: ارقام فارسی/عربی/لاتین، جداکنندهٔ هزارگان
    فارسی (٬) و لاتین (,) و فاصله، ممیز (٫ یا .)، علامت منفی (خط تیره، «−» یا
    پرانتز حسابداری)، پسوند ریال/تومان، ضریب نوشتاری (میلیون/میلیارد) و عددِ
    نوشتاری («دو میلیون و پانصد هزار»). اگر هیچ عدد معتبری نبود None برمی‌گردد
    تا هرگز عدد ساختگی وارد فاکتور نشود.
    """
    if text is None:
        return None
    raw = normalize_number_text(text)
    if not raw:
        return None

    # درصد، مبلغ نیست: برگرداندن نرخ به‌جای مبلغ همان خطایی است که سطر
    # «مالیات بر ارزش افزوده (۹٪)» را خراب می‌کرد
    if re.search(r'[٪%]', raw):
        return None

    negative = False
    stripped = raw.strip()
    if stripped.startswith('(') and stripped.endswith(')'):
        negative, stripped = True, stripped[1:-1]
    if stripped.startswith('-') or stripped.startswith('−') or stripped.startswith('—'):
        negative, stripped = True, stripped[1:]
    if stripped.endswith('-') or stripped.endswith('−'):
        negative, stripped = True, stripped[:-1]

    has_any_digit = any(ch.isdigit() for ch in stripped)
    if not has_any_digit:
        if not allow_words:
            return None
        words_value = parse_number_words(stripped)
        return None if words_value is None else (-words_value if negative else words_value)

    # رقم + ضریب نوشتاری: «۲.۵ میلیون»، «3 میلیارد»
    for name, scale in _UNIT_SCALES:
        match = re.fullmatch(rf'\s*([0-9][0-9{_SEP_CHARS}.٫]*)\s*{name}\s*', stripped)
        if match:
            base_text = match.group(1).replace('٬', '').replace('،', '').replace(',', '')
            base_text = ''.join(ch for ch in base_text if ch.isdigit() or ch in ' .٫')
            base_text = base_text.replace('٫', '.').strip()
            try:
                base = float(base_text)
            except ValueError:
                return None
            value = int(round(base * scale))
            return -value if negative else value

    # پاک‌سازی: نویسه‌های غیرعددی حذف، حرف‌های شبیه‌رقم جایگزین
    body = _digits_of(stripped)
    body = ''.join(ch for ch in body if ch.isdigit() or ch in '.,٬،/')

    # ممیز: یک جداکنندهٔ تنها با ۱ یا ۲ رقم بعدش ممیز است؛ سه رقم یعنی هزارگان
    body = body.replace('٬', ',').replace('،', ',')
    if body.count('.') + body.count(',') > 0:
        last_sep = max(body.rfind('.'), body.rfind(','))
        decimals = len(body) - last_sep - 1
        if last_sep > 0 and 0 < decimals <= 2 and body.count('.') + body.count(',') == 1:
            body = body[:last_sep] + '.' + body[last_sep + 1:]
        else:
            body = body.replace('.', '').replace(',', '')
    body = body.replace('/', '')
    if not body or body == '.':
        return None
    if body.count('.') > 1:
        return None
    try:
        value = float(body)
    except ValueError:
        return None
    if value != value or value in (float('inf'), float('-inf')):
        return None
    if abs(value) > 10 ** 16:
        return None
    # گرد کردنِ نیم‌به‌بالا (نه بانک‌داری): ۱۲٫۵ → ۱۳
    rounded = int(math.floor(value + 0.5)) if value >= 0 else -int(math.floor(-value + 0.5))
    return -rounded if negative else rounded


def parse_percent(text):
    """نرخ درصدی از متنی مثل «۹٪»، «(%9)»، «۹ درصد» → 9 (یا None)."""
    if text is None:
        return None
    raw = normalize_number_text(text)
    if not raw:
        return None
    raw = raw.replace('درصد', '٪')
    match = re.search(r'([0-9]{1,3})\s*[٪%]|[٪%]\s*[)\]}]?\s*\(?\s*([0-9]{1,3})', raw)
    if not match:
        return None
    value = int(next(group for group in match.groups() if group))
    return value if 0 < value <= 100 else None


def format_amount(value, separator='٬'):
    """عدد → رشتهٔ خوانا: 1234567 → «۱٬۲۳۴٬۵۶۷» (یا با ارقام لاتین)."""
    if value is None:
        return ''
    try:
        number = int(round(float(value)))
    except (TypeError, ValueError):
        return ''
    sign = '-' if number < 0 else ''
    groups = []
    digits = str(abs(number))
    while digits:
        groups.append(digits[-3:])
        digits = digits[:-3]
    formatted = separator.join(reversed(groups))
    return (sign + formatted).translate(LATIN_TO_FA)


def digits_only(text):
    """فقط ارقام یک متن، به لاتین: «۱۲۳/۴۵۶» → «123456»."""
    return ''.join(ch for ch in _digits_of(normalize_number_text(text)) if ch.isdigit())


