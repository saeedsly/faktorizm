def _plurals(words):
    """شکل‌های جمعِ رایج: «کالا» → کالاها / کالاهای."""
    out = set()
    for word in words:
        if ' ' in word or len(word) < 4 or len(word) > 11:
            continue
        out.add(word + 'ها')
        out.add(word + 'های')
    return out


